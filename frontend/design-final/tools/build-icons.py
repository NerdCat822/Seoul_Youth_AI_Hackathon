# Builds assets/js/icons.js from Remix Icon SVGs (node_modules/remixicon)
import glob, json, os, re
NAMES = {
 'user':'user-3-fill','chevron-down':'arrow-down-s-line','chevron-up':'arrow-up-s-line','arrow-up':'arrow-up-line','sparkling':'sparkling-2-fill',
 'add':'add-line','add-circle':'add-circle-line','mic':'mic-fill','chevron-right':'arrow-right-s-line','chevron-left':'arrow-left-s-line',
 'check':'check-line','file-excel':'file-excel-2-line','close':'close-line','checkbox-circle':'checkbox-circle-fill','error-warning':'error-warning-fill',
 'question':'question-fill','dot':'checkbox-blank-circle-fill','store':'store-2-line','settings':'settings-3-line','logout':'logout-box-r-line',
 'open':'external-link-line','upload':'upload-2-line','bell':'notification-3-fill','chat':'message-3-fill','menu':'menu-line','calendar':'calendar-line',
 'image':'image-line','search':'search-line','delete':'delete-bin-line','more':'more-2-fill','arrow-left':'arrow-left-line',
 'collapse':'collapse-diagonal-line','expand':'expand-diagonal-line','time':'time-line','file-list':'file-list-3-line','attachment':'attachment-2',
 'info':'information-line','inbox':'inbox-archive-line','calendar-check':'calendar-check-line','lightbulb':'lightbulb-line','pencil':'pencil-line',
 'camera':'camera-line','keyboard':'keyboard-line','file-text':'file-text-line',
}
out = {}
for key, fname in NAMES.items():
    path = glob.glob(f'node_modules/remixicon/icons/**/{fname}.svg', recursive=True)[0]
    svg = open(path).read()
    inner = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1)
    out[key] = inner.replace('<path ', '<path fill="currentColor" ')
open('assets/js/icons.js', 'w').write('/* Remix Icon (Apache-2.0) paths, generated by tools/build-icons.py */\nwindow.ICONS = ' + json.dumps(out, ensure_ascii=False) + ';\n')
print(len(out), os.path.getsize('assets/js/icons.js'))
